"""Generate an analyst-readable Markdown intel report (renders nicely on GitHub)."""

from __future__ import annotations

import re
from collections import defaultdict
from datetime import datetime, timezone

from .hunt import Hit
from .store import StixStore

ACTOR_TYPES = ("threat-actor", "intrusion-set", "campaign")
MAX_ROWS = 60
MAX_GRAPH_EDGES = 60


def attack_id(obj: dict) -> str:
    for ref in obj.get("external_references", []):
        if ref.get("source_name", "").startswith("mitre") and ref.get("external_id"):
            return ref["external_id"]
    return ""


def _label(obj: dict | None) -> str:
    if not obj:
        return "?"
    name = obj.get("name") or obj["id"].split("--")[0]
    aid = attack_id(obj)
    return f"{aid} {name}" if aid else name


def _md(text: str) -> str:
    return (text or "").replace("|", "\\|").replace("\n", " ")


def build_report(store: StixStore, title: str = "Threat Intelligence Summary", hits: list[Hit] | None = None) -> str:
    lines: list[str] = []
    add = lines.append
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    counts = store.counts_by_type()

    add(f"# {title}\n")
    add(f"_Generated by stixflow on {now} from `{store.path}`_\n")

    # --- summary -----------------------------------------------------------
    add("## Collection summary\n")
    add("| STIX type | Count |\n|---|---:|")
    for t, n in counts.items():
        add(f"| `{t}` | {n} |")
    add("")

    # --- hunt results (most actionable, so near the top) -------------------
    if hits is not None:
        add("## Hunt results\n")
        if not hits:
            add("No indicator matches in the supplied logs.\n")
        else:
            add(f"**{len(hits)} match(es)** across {len({h.line_no for h in hits})} log line(s).\n")
            add("| Line | Observed | Matched indicator | Linked to |\n|---:|---|---|---|")
            for h in hits[:MAX_ROWS]:
                ctx = "; ".join(h.context[:3]) or "-"
                add(f"| {h.line_no} | `{h.observed}` | {_md(h.indicator_name)} (`{h.matched}`) | {_md(ctx)} |")
            add("")

    # --- adversaries -------------------------------------------------------
    actors = list(store.iter_objects(list(ACTOR_TYPES)))
    if actors:
        add("## Adversary activity\n")
        for a in actors[:MAX_ROWS]:
            add(f"### {a.get('name', a['id'])} (`{a['type']}`)\n")
            if a.get("description"):
                add(f"{a['description']}\n")
            grouped: dict[str, list[str]] = defaultdict(list)
            for direction, rtype, other_id in store.neighbors(a["id"]):
                other = store.get(other_id)
                if not other or other.get("revoked") or other["type"] == "indicator":
                    continue
                key = rtype if direction == "out" else f"{rtype} (inbound)"
                grouped[key].append(_label(other))
            for rtype, names in sorted(grouped.items()):
                add(f"- **{rtype}:** {', '.join(sorted(set(names))[:15])}")
            add("")

    # --- ATT&CK techniques & mitigations -----------------------------------
    techniques = list(store.iter_objects(["attack-pattern"]))
    if techniques:
        add("## ATT&CK techniques\n")
        add("| ID | Technique | Used by | Mitigations |\n|---|---|---|---|")
        rows = []
        for ap in techniques:
            used_by, mitigations = [], []
            for direction, rtype, other_id in store.neighbors(ap["id"]):
                if direction != "in":
                    continue
                other = store.get(other_id)
                if not other or other.get("revoked"):
                    continue
                if rtype == "uses":
                    used_by.append(other.get("name", "?"))
                elif rtype == "mitigates":
                    mitigations.append(_label(other))
            rows.append((len(used_by), ap, used_by, mitigations))
        # most-used techniques first; skip unused ones when the set is large (e.g. full ATT&CK)
        rows.sort(key=lambda r: (-r[0], attack_id(r[1])))
        shown = [r for r in rows if r[0] > 0 or len(rows) <= MAX_ROWS][:MAX_ROWS]
        for _n, ap, used_by, mits in shown:
            add(f"| {attack_id(ap)} | {_md(ap.get('name', ''))} | {_md(', '.join(sorted(used_by)[:6])) or '-'} "
                f"| {_md(', '.join(sorted(mits)[:4])) or '-'} |")
        if len(rows) > len(shown):
            add(f"\n_{len(rows) - len(shown)} additional technique(s) omitted._")
        add("")

    # --- indicators --------------------------------------------------------
    obs = store.observables()
    if obs:
        add("## Indicators of compromise\n")
        add("| Type | Value | Indicator | Indicates |\n|---|---|---|---|")
        for r in obs[:MAX_ROWS]:
            targets = [_label(store.get(o)) for d, rt, o in store.neighbors(r["indicator_id"])
                       if d == "out" and rt == "indicates"]
            add(f"| {r['ioc_type']} | `{r['value']}` | {_md(r['indicator_name'])} | {_md(', '.join(targets)) or '-'} |")
        if len(obs) > MAX_ROWS:
            add(f"\n_{len(obs) - MAX_ROWS} more - use `stixflow export` for the full list._")
        add("")

    # --- relationship graph ------------------------------------------------
    graph = mermaid_graph(store)
    if graph:
        add("## Relationship graph\n")
        add("```mermaid")
        add(graph)
        add("```\n")

    return "\n".join(lines)


def mermaid_graph(store: StixStore, max_edges: int = MAX_GRAPH_EDGES) -> str:
    """Mermaid flowchart of SDO-to-SDO relationships (indicators collapsed out for readability)."""
    rows = store.conn.execute(
        "SELECT r.source_ref, r.relationship_type, r.target_ref FROM relationships r "
        "JOIN objects s ON s.id = r.source_ref JOIN objects t ON t.id = r.target_ref "
        "WHERE s.type != 'indicator' AND t.type != 'indicator' AND s.revoked = 0 AND t.revoked = 0 "
        "ORDER BY CASE s.type WHEN 'campaign' THEN 0 WHEN 'intrusion-set' THEN 1 WHEN 'threat-actor' THEN 2 "
        "WHEN 'malware' THEN 3 WHEN 'tool' THEN 4 ELSE 5 END"
    ).fetchall()[:max_edges]
    if not rows:
        return ""

    ids: dict[str, str] = {}

    def node(obj_id: str) -> str:
        if obj_id not in ids:
            ids[obj_id] = f"n{len(ids)}"
        return ids[obj_id]

    shapes = {
        "threat-actor": ("[/", "/]"), "intrusion-set": ("{{", "}}"), "campaign": ("([", "])"),
        "malware": ("[[", "]]"), "tool": ("[[", "]]"), "attack-pattern": ("[", "]"),
        "course-of-action": ("(", ")"), "identity": ("[(", ")]"), "vulnerability": (">", "]"),
    }
    out = ["flowchart LR"]
    edges = []
    for r in rows:
        edges.append(f"  {node(r['source_ref'])} -->|{r['relationship_type']}| {node(r['target_ref'])}")
    for obj_id, nid in ids.items():
        obj = store.get(obj_id) or {"id": obj_id}
        left, right = shapes.get(obj.get("type", ""), ("[", "]"))
        label = re.sub(r'["\[\]{}()<>|]', "", _label(obj))[:40]
        out.append(f'  {nid}{left}"{label}"{right}')
    return "\n".join(out + edges)
